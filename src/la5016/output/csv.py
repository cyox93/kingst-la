"""Comma-separated values output.

Ported from libsigrok src/output/csv.c (gen_header(), process_logic(),
dump_saved_values(), save_gnuplot()) for logic data. Quirks kept: the
default label "units" names logic columns "logic" and the time column by
its unit; the time column counts *printed* rows (so it skips nothing when
dedup drops rows); multi-byte value separators lose only their last byte
at the end of a row.

libsigrok applies dedup per logic packet (first and last row of every
packet are always printed). Here dedup behaves as if the data before and
after the trigger each arrived as one packet, so the output does not
depend on how feed() chunks the samples.
"""

from __future__ import annotations

from typing import BinaryIO, List, Mapping, Optional

import numpy as np

from ..pipeline import Meta
from ._common import (DEVICE_CHANNELS, DRIVER_LONGNAME, PACKAGE_VERSION,
                      as_samples, assemble, channel_bits, const_block,
                      ctime_now, parse_options, samplerate_string, uint_block)

XLABELS = ["samples", "milliseconds", "microseconds", "nanoseconds",
           "picoseconds", "femtoseconds", "attoseconds"]

OPTIONS = {
    "gnuplot": ("str", ""),
    "scale": ("bool", True),
    "value": ("str", ","),
    "record": ("str", "\n"),
    "frame": ("str", "\n"),
    "comment": ("str", ";"),
    "header": ("bool", True),
    "label": (("units", "channel", "off"), "units"),
    "time": ("bool", False),
    "trigger": ("bool", False),
    "dedup": ("bool", False),
}


class CsvOutput:
    NAME = "csv"

    def __init__(self, out: BinaryIO, options: Optional[Mapping[str, object]] = None):
        o = parse_options(self.NAME, OPTIONS, options)
        self.out = out
        self.gnuplot = str(o["gnuplot"])
        self.scale = bool(o["scale"])
        self.value = str(o["value"]).encode()
        self.record = str(o["record"]).encode()
        self.comment = str(o["comment"])
        self.header = bool(o["header"])
        self.time = bool(o["time"])
        self.do_trigger = bool(o["trigger"])
        self.dedup = bool(o["dedup"]) and self.time
        self.label_do = self.label_did = o["label"] != "off"
        self.label_names = self.label_do and o["label"] != "units"
        self.did_header = False
        self.trig_pending = False
        self.out_count = 0
        # dedup state: held-back last sample, its decision, segment predecessor
        self.held: Optional[int] = None
        self.held_keep = False
        self.seg_prev: Optional[int] = None

    def begin(self, meta: Meta) -> None:
        self.meta = meta
        self.channels = list(meta.channels)
        self.mask = np.uint16(sum(1 << ch.index for ch in self.channels) & 0xFFFF)
        self.sample_rate = meta.samplerate
        i, self.sample_scale = 0, 1
        while self.sample_scale < self.sample_rate:
            i += 1
            self.sample_scale *= 1000
        self.xlabel = XLABELS[i] if i < len(XLABELS) else "(null)"
        if self.header and not self.did_header:
            c = self.comment
            s = f"{c} CSV generated by {PACKAGE_VERSION}\n"
            s += f"{c} from {DRIVER_LONGNAME} on {ctime_now()}\n"
            s += f"{c} Channels ({len(self.channels)}/{DEVICE_CHANNELS}):"
            s += "".join(f" {ch.name}," for ch in self.channels)
            s = s[:-1] + "\n"
            if self.sample_rate:
                s += f"{c} Samplerate: {samplerate_string(self.sample_rate)}\n"
            self.did_header = True
            self.out.write(s.encode())

    # -- data ---------------------------------------------------------------

    def feed(self, samples: np.ndarray) -> None:
        samples = as_samples(samples)
        if not samples.size:
            return
        if not self.dedup:
            self._emit(samples)
            return
        parts: List[np.ndarray] = []
        if self.held is not None:
            if self.held_keep:
                parts.append(np.array([self.held], dtype=np.uint16))
            self.seg_prev = self.held & int(self.mask)
        m = samples & self.mask
        prevs = np.empty_like(m)
        prevs[1:] = m[:-1]
        if self.seg_prev is None:
            prevs[0] = ~m[0]  # first row of a segment is always printed
        else:
            prevs[0] = self.seg_prev
        keep = m != prevs
        parts.append(samples[:-1][keep[:-1]])
        self.held = int(samples[-1])
        self.held_keep = bool(keep[-1])
        self._emit(np.concatenate(parts))

    def _flush_held(self) -> None:
        if self.held is not None:
            self._emit(np.array([self.held], dtype=np.uint16))
        self.held = None
        self.seg_prev = None

    def trigger(self) -> None:
        if self.dedup:
            self._flush_held()  # last row of the pre-trigger "packet"
        self.trig_pending = True

    def end(self) -> None:
        if self.dedup:
            self._flush_held()
        if self.gnuplot:
            self._save_gnuplot()

    def _labels(self) -> bytes:
        v = self.value
        s = b""
        if self.time:
            s += (b"Time" if self.label_names else self.xlabel.encode()) + v
        for ch in self.channels:
            s += (ch.name.encode() if self.label_names else b"logic") + v
        if self.do_trigger:
            s += b"Trigger" + v
        return s[:-1] + self.record

    def _emit(self, rows: np.ndarray) -> None:
        n = rows.size
        if not n:
            return
        out = b""
        if self.label_do:
            out += self._labels()
            self.label_do = False
        blocks = []
        if self.time:
            if self.sample_rate:
                cnt = np.arange(self.out_count, self.out_count + n, dtype=np.uint64)
                t = cnt.astype(np.float64) / self.sample_rate * self.sample_scale
                blocks.append(uint_block(t.astype(np.uint64)))
            else:
                blocks.append(const_block(n, b"0"))
            blocks.append(const_block(n, self.value))
        self.out_count += n
        for ch in self.channels:
            blocks.append(((channel_bits(rows, ch.index) + ord("0"))[:, None], None))
            blocks.append(const_block(n, self.value))
        if self.do_trigger:
            trig = np.full((n, 1), ord("0"), dtype=np.uint8)
            if self.trig_pending:
                trig[0, 0] = ord("1")
                self.trig_pending = False
            blocks.append((trig, None))
            blocks.append(const_block(n, self.value))
        # Drop the last byte of each row (g_string_truncate), add the record.
        blocks = _drop_last_byte(blocks)
        blocks.append(const_block(n, self.record))
        self.out.write(out + assemble(blocks))

    def _save_gnuplot(self) -> None:
        num = len(self.channels)
        if not num:
            return
        v = self.value.decode()
        s = f"set datafile separator '{v}'\n"
        if self.label_did:
            s += "set key autotitle columnhead\n"
        if self.time:
            s += f"set xlabel '{self.xlabel}'\n"
        s += "plot "
        # Logic channels: min 0, max 1, so every graph has height 1.
        step = 1.0 / 4
        offset = step
        mins = [0.0] * num
        for i in range(num - 1, -1, -1):
            mins[i] = offset
            offset += step + 1.0
        t = int(self.time)
        for i in range(num):
            s += "ARG1 "
            if self.did_header:
                s += "skip 4 "
            s += "using %u:($%u * %g + %g), " % (t, i + 1 + t, 1.0, mins[i])
        with open(self.gnuplot, "wb") as f:
            f.write(s[:-2].encode())


def _drop_last_byte(blocks):
    blocks = list(blocks)
    while blocks and blocks[-1][0].shape[1] == 0:
        blocks.pop()
    if not blocks:
        return blocks
    arr, mask = blocks.pop()
    if arr.shape[1] > 1:
        # The last column is always printed (separator byte, 1-byte field or
        # the units digit of the time), so slicing it off drops one byte.
        blocks.append((arr[:, :-1], None if mask is None else mask[:, :-1]))
    return blocks
