GOLDEN = Path(__file__).parent / "golden"

# Test signal (40 samples at 1 MHz), see tests/golden/README.md.
BITS = {
    0: "0011" * 10,                                  # CH0
    1: "00001111" * 5,                               # CH1
    3: "00000" + "1" * 15 + "0" * 20,                # CH3, renamed SDA
    5: "0" * 25 + "11" + "0" * 13,                   # CH5, disabled
    9: "0" * 12 + "1" + "0" * 20 + "1" * 7,          # CH9
}
SAMPLES = np.array([sum(int(b[i]) << idx for idx, b in BITS.items()) for i in range(40)],
                   dtype=np.uint16)
META = Meta(samplerate=1_000_000,
            channels=[Channel(0, "CH0"), Channel(1, "CH1"), Channel(3, "SDA"), Channel(9, "CH9")])
TRIGGER_AT = 21

# Lines carrying the date or the package version.
VOLATILE = re.compile(rb"^(kingst-la .*|; CSV generated by .*|; from .*|\$date .*|\$version .*)$",
                      re.M)


def mask(data: bytes) -> bytes:
    return VOLATILE.sub(b"<masked>", data)


def run(fmt, options=None, samples=SAMPLES, meta=META, trigger_at=None, chunks=None):
    buf = io.BytesIO()
    sink = create(fmt, buf, options or {})
    sink.begin(meta)
    pieces = [samples] if trigger_at is None else [samples[:trigger_at], samples[trigger_at:]]
    for n, piece in enumerate(pieces):
        if n:
            sink.trigger()
        if chunks is None:
            sink.feed(piece)
        else:
            pos = 0
            for size in chunks(piece.size):
                sink.feed(piece[pos:pos + size])
                pos += size
            assert pos == piece.size
    sink.end()
    return buf.getvalue()


GOLDEN_CASES = [
    ("bits.txt", "bits", {}, None),
    ("bits_trigger.txt", "bits", {"width": "16"}, TRIGGER_AT),
    ("hex.txt", "hex", {}, None),
    ("hex_trigger.txt", "hex", {"width": "12"}, TRIGGER_AT),
    ("csv.csv", "csv", {}, None),
    ("csv_trigger.csv", "csv", {"time": "true", "trigger": "true"}, TRIGGER_AT),
    ("csv_dedup_trigger.csv", "csv",
     {"label": "channel", "time": "yes", "dedup": "true", "trigger": "true"}, TRIGGER_AT),
    ("vcd.vcd", "vcd", {}, None),
    ("vcd_trigger.vcd", "vcd", {}, TRIGGER_AT),
    ("binary.bin", "binary", {}, None),
    ("binary_trigger.bin", "binary", {}, TRIGGER_AT),
]


@pytest.mark.parametrize("name,fmt,options,trigger_at", GOLDEN_CASES,
                         ids=[c[0] for c in GOLDEN_CASES])
def test_golden(name, fmt, options, trigger_at):
    expected = (GOLDEN / name).read_bytes()
    actual = run(fmt, options, trigger_at=trigger_at)
    assert mask(actual) == mask(expected)


def test_golden_readme_lists_all_files():
    readme = (GOLDEN / "README.md").read_text()
    for name, *_ in GOLDEN_CASES:
        assert f"`{name}`" in readme


def test_volatile_lines():
    version = f"kingst-la {kingst_la.__version__}".encode()
    assert run("bits").splitlines()[0] == version
    vcd = run("vcd").splitlines()
    assert vcd[1] == b"$version " + version + b" $end"
    assert re.fullmatch(rb"\$date \w{3} \w{3} [ \d]\d \d\d:\d\d:\d\d \d{4} \$end", vcd[0])
    csv = run("csv").splitlines()
    assert csv[0] == b"; CSV generated by " + version
    assert re.fullmatch(rb"; from Kingst LA2016 on \w{3} \w{3} [ \d]\d \d\d:\d\d:\d\d \d{4}",
                        csv[1])


# ---- chunking invariance -------------------------------------------------

def _random_signal(n=3000, seed=1):
    rng = np.random.default_rng(seed)
    runs = rng.integers(1, 40, size=n)
    vals = rng.integers(0, 1 << 16, size=n, dtype=np.uint16)
    return np.repeat(vals, runs)[:n].astype(np.uint16)


CHUNK_CASES = [
    ("bits", {}), ("bits", {"width": "12"}), ("bits", {"width": "0"}),
    ("hex", {}), ("hex", {"width": "12"}), ("hex", {"width": "5"}), ("hex", {"width": "0"}),
    ("csv", {}), ("csv", {"time": "true", "trigger": "true"}),
    ("csv", {"time": "true", "dedup": "true", "trigger": "true", "label": "channel"}),
    ("csv", {"value": "", "header": "false"}),
    ("vcd", {}), ("binary", {}),
]


@pytest.mark.parametrize("fmt,options", CHUNK_CASES)
@pytest.mark.parametrize("trigger_at", [None, 0, 777, 3000])
def test_chunking_invariance(fmt, options, trigger_at):
    samples = _random_signal()
    meta = Meta(samplerate=1_000_000, channels=[Channel(15, "X"), Channel(0, "CH0"),
                                                 Channel(7, "CH7"), Channel(8, "CH8")])
    whole = mask(run(fmt, options, samples, meta, trigger_at))
    rng = np.random.default_rng(7)

    def random_chunks(n):
        sizes = [0]
        while sum(sizes) < n:
            sizes.append(int(rng.integers(0, 50)))
        sizes[-1] -= sum(sizes) - n
        return sizes

    for chunks in (lambda n: [1] * n, random_chunks, lambda n: [0, n, 0]):
        assert mask(run(fmt, options, samples, meta, trigger_at, chunks)) == whole


# ---- format details --------------------------------------------------------

def test_bits_width_zero_is_one_line():
    out = run("bits", {"width": "0"}).decode().splitlines()
    assert out[2] == "CH0:" + " ".join(["00110011"] * 5) + " "
    assert len(out) == 6


def test_bits_marker_only_on_full_line_flush():
    # Default width 64 > 40 samples: libsigrok never prints the marker.
    assert b"T:" not in run("bits", trigger_at=TRIGGER_AT)


def test_vcd_500mhz_timescale():
    meta = Meta(samplerate=500_000_000, channels=[Channel(0, "CH0")])
    out = run("vcd", samples=np.array([0, 1, 1, 0], dtype=np.uint16), meta=meta).decode()
    assert "$timescale 1 ns $end\n" in out
    assert "  Acquisition with 1/16 channels at 500 MHz\n" in out
    assert out.endswith("$enddefinitions $end\n\n#0  0!\n#2  1!\n#6  0!\n#8\n")


def test_vcd_empty_capture():
    out = run("vcd", samples=np.zeros(0, dtype=np.uint16)).decode()
    assert out.endswith("$enddefinitions $end\n\n#0\n")


def test_vcd_identifiers():
    assert vcd_identifier(0) == "!"
    assert vcd_identifier(93) == "~"
    assert vcd_identifier(94) == "aa"
    assert vcd_identifier(95) == "ab"
    assert vcd_identifier(94 + 676) == "aaa"


def test_csv_gnuplot(tmp_path):
    path = tmp_path / "plot.gpi"
    run("csv", {"gnuplot": str(path), "time": "true"})
    assert path.read_text() == (
        "set datafile separator ','\n"
        "set key autotitle columnhead\n"
        "set xlabel 'microseconds'\n"
        "plot ARG1 skip 4 using 1:($2 * 1 + 4), ARG1 skip 4 using 1:($3 * 1 + 2.75), "
        "ARG1 skip 4 using 1:($4 * 1 + 1.5), ARG1 skip 4 using 1:($5 * 1 + 0.25)")


def test_csv_separators_and_no_header():
    out = run("csv", {"header": "no", "label": "off", "value": "::", "record": "\r\n"},
              samples=SAMPLES[4:6])
    # g_string_truncate() drops only one byte of a multi-byte separator.
    assert out == b"0::1::0::0:\r\n0::1::1::0:\r\n"


def test_csv_time_scale_500mhz():
    meta = Meta(samplerate=500_000_000, channels=[Channel(0, "CH0")])
    out = run("csv", {"time": "true", "header": "false"},
              samples=np.array([0, 1, 1], dtype=np.uint16), meta=meta)
    assert out == b"nanoseconds,logic\n0,0\n2,1\n4,1\n"


# ---- options ---------------------------------------------------------------

def test_formats():
    assert set(FORMATS) == {"bits", "hex", "csv", "vcd", "binary", "srzip"}
    with pytest.raises(ValueError, match="unknown output format"):
        create("sr", io.BytesIO(), {})


@pytest.mark.parametrize("fmt,accepted", [
    ("bits", "width"), ("hex", "width"),
    ("csv", "gnuplot, scale, value, record, frame, comment, header, label, time, "
            "trigger, dedup"),
    ("vcd", "(none)"), ("binary", "(none)"), ("srzip", "(none)"),
])
def test_unknown_option(fmt, accepted):
    with pytest.raises(ValueError) as exc:
        create(fmt, io.BytesIO(), {"bogus": "1"})
    assert "bogus" in str(exc.value)
    assert f"accepted: {accepted}" in str(exc.value)


@pytest.mark.parametrize("fmt,options", [
    ("bits", {"width": "abc"}), ("hex", {"width": "-1"}), ("bits", {"width": str(2**32)}),
    ("csv", {"time": "maybe"}), ("csv", {"label": "names"}),
])
def test_invalid_option_values(fmt, options):
    with pytest.raises(ValueError):
        create(fmt, io.BytesIO(), options)


@pytest.mark.parametrize("value,expected", [
    ("true", True), ("yes", True), ("", True), ("TRUE", True), ("1", True),
    ("false", False), ("no", False), ("0", False), ("off", False),
])
def test_bool_option(value, expected):
    sink = create("csv", io.BytesIO(), {"time": value})
    assert sink.time is expected


def test_option_defaults():
    csv = create("csv", io.BytesIO(), {})
    assert (csv.value, csv.record, csv.comment, csv.header, csv.time, csv.do_trigger,
            csv.dedup, csv.label_names) == (b",", b"\n", ";", True, False, False, False, False)
    assert create("bits", io.BytesIO(), {}).spl == 64
    assert create("hex", io.BytesIO(), {}).spl == 192


